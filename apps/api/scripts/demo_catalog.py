"""Demo stores and their products. Each product becomes one variant per combination of options."""

from dataclasses import dataclass, field


@dataclass
class DemoProduct:
    name: str
    category: str
    description: str
    price: int  # NPR, price of the cheapest variant
    options: dict[str, list[str]]  # option name -> values, e.g. {"size": ["S", "M"]}
    extra_price: dict[str, int] = field(default_factory=dict)  # option value -> added to price


@dataclass
class DemoStore:
    name: str
    sku_prefix: str
    products: list[DemoProduct]


